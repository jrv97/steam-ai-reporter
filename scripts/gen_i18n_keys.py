"""Generate typed message keys from the English catalogs.

For each catalog this writes a TypeScript module with:
- `MessageParams`: every message key but the BUILD_ONLY_KEYS, mapped to the named placeholders
  it takes;
- `PluralParams`: every plural base key (one with an `_other` form), mapped to its placeholders
  other than `count`, which `plural()` fills in;
- `MessageKey` and `PluralKey`, the key unions.

So `t("missing_key")` or a wrong placeholder fails the type check. The outputs are gitignored and
regenerated by the tasks that need them.

Usage: gen_i18n_keys.py
"""

from pathlib import Path

from catalogs import BUILD_ONLY_KEYS, DEFAULT_LOCALE, Catalog, load, plural_base, plural_bases
from repo import ROOT, fail

TARGETS = (
    (ROOT / "src" / "locales", ROOT / "src" / "core" / "i18n" / "keys.gen.ts"),
    (ROOT / "tests" / "locales", ROOT / "tests" / "locales" / "keys.gen.ts"),
)
COUNT = "count"


def params_type(names: tuple[str, ...]) -> str:
    if not names:
        return "NoParams"
    fields = "; ".join(f"readonly {name}: string" for name in names)
    return f"{{ {fields} }}"


def interface(name: str, members: dict[str, tuple[str, ...]]) -> list[str]:
    if not members:
        return [f"export type {name} = NoParams;"]
    lines = [f"export interface {name} {{"]
    lines += [f"  readonly {key}: {params_type(names)};" for key, names in sorted(members.items())]
    lines.append("}")
    return lines


def render(catalog: Catalog, source: Path) -> str:
    bases = plural_bases(catalog)
    messages: dict[str, tuple[str, ...]] = {}
    plurals: dict[str, tuple[str, ...]] = {}
    for key, entry in catalog.items():
        if key in BUILD_ONLY_KEYS:
            continue
        base = plural_base(key)
        if base is not None and base in bases:
            if key == f"{base}_other":
                plurals[base] = tuple(name for name in entry.placeholders if name != COUNT)
        else:
            messages[key] = entry.placeholders
    for base in bases:
        if f"{base}_one" not in catalog:
            fail(f"{source}: plural {base} needs both _one and _other")
    relative = source.relative_to(ROOT).as_posix()
    lines = [
        f"// Generated by scripts/gen_i18n_keys.py from {relative}. Do not edit.",
        "",
        "type NoParams = Readonly<Record<string, never>>;",
        "",
        *interface("MessageParams", messages),
        "",
        *interface("PluralParams", plurals),
        "",
        "export type MessageKey = keyof MessageParams;",
        "export type PluralKey = keyof PluralParams;",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    for locales, output in TARGETS:
        source = locales / DEFAULT_LOCALE / "messages.json"
        text = render(load(source), source)
        if not output.is_file() or output.read_text(encoding="utf-8") != text:
            output.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
