"""Generate the catalogs core ships, with only what the runtime reads.

Writes src/core/i18n/shipped.gen.ts: `SHIPPED_CATALOGS`, every catalog under src/locales/ by
locale code, each entry reduced to its `message`. Descriptions and placeholder examples are for
translators and stay out of the bundles; the runtime substitutes `$name$` by name, so it needs no
placeholder table either. The output is gitignored and regenerated by the tasks that need it.

Usage: gen_catalogs.py
"""

import json

from catalogs import DEFAULT_LOCALE, load
from repo import ROOT, fail

LOCALES = ROOT / "src" / "locales"
OUTPUT = ROOT / "src" / "core" / "i18n" / "shipped.gen.ts"


def render() -> str:
    sources = sorted(LOCALES.glob("*/messages.json"))
    if not any(source.parent.name == DEFAULT_LOCALE for source in sources):
        fail(f"missing the {DEFAULT_LOCALE} catalog in {LOCALES}")
    lines = [
        "// Generated by scripts/gen_catalogs.py from src/locales/*/messages.json. Do not edit.",
        "",
        'import type { Catalogs } from "./catalog";',
        "",
        "/** The shipped catalogs by locale code, messages only. */",
        "export const SHIPPED_CATALOGS: Catalogs = {",
    ]
    for source in sources:
        lines.append(f"  {json.dumps(source.parent.name)}: {{")
        for entry in load(source).values():
            message = json.dumps(entry.message, ensure_ascii=False)
            lines.append(f"    {json.dumps(entry.key)}: {{ message: {message} }},")
        lines.append("  },")
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> None:
    text = render()
    if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
