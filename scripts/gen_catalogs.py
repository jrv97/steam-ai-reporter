"""Generate the catalogs core and each shipped bundle carry, with only what the runtime reads.

Writes src/core/i18n/shipped.gen.ts: `SHIPPED_CATALOGS`, every catalog under src/locales/ by
locale code, each entry reduced to its `message`. Descriptions and placeholder examples are for
translators and stay out of the bundles; the runtime substitutes `$name$` by name, so it needs no
placeholder table either. Tests and the dev bundle use it.

Then, for each shipped entry in SURFACES, writes `<entry>.catalogs.gen.ts` next to it: `CATALOGS`,
the same locales with only the messages that entry's bundle reads. esbuild bundles each entry once
into a temporary folder, and bundle_keys.py reads the key literals of that output, so the
projection follows the import graph after tree shaking and needs no list of keys per surface. A
computed key fails here. check_bundle.py checks the built bundles against the same reading.

The outputs are gitignored and regenerated by the tasks that need them; a file is written only
when its text changes.

Usage: gen_catalogs.py
"""

import json
import tempfile
from collections.abc import Mapping, Set
from pathlib import Path

from build import Bundle, run_esbuild
from bundle_keys import computed_keys, message_names, name_of, read_names
from catalogs import DEFAULT_LOCALE, Catalog, load, plural_bases
from repo import ROOT, fail

LOCALES = ROOT / "src" / "locales"
I18N = ROOT / "src" / "core" / "i18n"
OUTPUT = I18N / "shipped.gen.ts"
SURFACE_SUFFIX = ".catalogs.gen.ts"
# The shipped bundle entries: the content script, the options page and popup, and the userscript.
SURFACES = (
    ROOT / "src" / "platform" / "extension" / "content.ts",
    ROOT / "src" / "platform" / "extension" / "options.ts",
    ROOT / "src" / "platform" / "userscript" / "main.ts",
)
HEADER = "// Generated by scripts/gen_catalogs.py from src/locales/*/messages.json. Do not edit."


def load_catalogs() -> dict[str, Catalog]:
    sources = sorted(LOCALES.glob("*/messages.json"))
    if not any(source.parent.name == DEFAULT_LOCALE for source in sources):
        fail(f"missing the {DEFAULT_LOCALE} catalog in {LOCALES}")
    return {source.parent.name: load(source) for source in sources}


def surface_module(entry: Path) -> Path:
    return entry.with_name(entry.stem + SURFACE_SUFFIX)


def catalog_import(module: Path) -> str:
    path = (I18N / "catalog").relative_to(module.parent, walk_up=True).as_posix()
    return path if path.startswith(".") else f"./{path}"


def render(
    catalogs: Mapping[str, Catalog], module: Path, name: str, doc: str, keep: Set[str] | None
) -> str:
    bases = plural_bases(catalogs[DEFAULT_LOCALE])
    lines = [
        HEADER,
        "",
        f"import type {{ Catalogs }} from {json.dumps(catalog_import(module))};",
        "",
        f"/** {doc} */",
        f"export const {name}: Catalogs = {{",
    ]
    for locale, catalog in catalogs.items():
        lines.append(f"  {json.dumps(locale)}: {{")
        for entry in catalog.values():
            if keep is None or name_of(entry.key, bases) in keep:
                message = json.dumps(entry.message, ensure_ascii=False)
                lines.append(f"    {json.dumps(entry.key)}: {{ message: {message} }},")
        lines.append("  },")
    lines += ["};", ""]
    return "\n".join(lines)


def write(path: Path, text: str) -> None:
    if not path.is_file() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")


def read_by_surface(catalogs: Mapping[str, Catalog]) -> dict[Path, set[str]]:
    """The message names each shipped entry's bundle reads, from one esbuild pass per entry."""
    names = message_names(catalogs[DEFAULT_LOCALE])
    for entry in SURFACES:
        module = surface_module(entry)
        if not module.is_file():
            write(
                module,
                render(
                    catalogs, module, "CATALOGS", "Empty until this script reads the bundle.", set()
                ),
            )
    with tempfile.TemporaryDirectory() as folder:
        bundles = {
            entry: Bundle(str(entry), Path(folder) / f"{index}.js")
            for index, entry in enumerate(SURFACES)
        }
        run_esbuild(list(bundles.values()), watch=False)
        scripts = {
            entry: bundle.outfile.read_text(encoding="utf-8") for entry, bundle in bundles.items()
        }
    problems = [
        f"{entry.relative_to(ROOT).as_posix()}: computed message key `{template}`"
        for entry, script in scripts.items()
        for template in computed_keys(script, names)
    ]
    if problems:
        print("\n".join(problems))
        fail(f"{len(problems)} computed key(s): name each message by its key literal")
    return {entry: read_names(script, names) for entry, script in scripts.items()}


def main() -> None:
    catalogs = load_catalogs()
    doc = "The shipped catalogs by locale code, messages only."
    write(OUTPUT, render(catalogs, OUTPUT, "SHIPPED_CATALOGS", doc, None))
    read = read_by_surface(catalogs)
    for entry, names in read.items():
        module = surface_module(entry)
        doc = f"The catalogs {entry.name}'s bundle carries: only the messages its code reads."
        write(module, render(catalogs, module, "CATALOGS", doc, names))


if __name__ == "__main__":
    main()
