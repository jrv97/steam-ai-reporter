"""Generate the UI stylesheets as TypeScript string constants.

Core injects its CSS at runtime (a document stylesheet for badges and the list filter, a shadow
root for the banner), so every target needs the CSS as text. This writes
src/core/ui/styles.gen.ts with one constant per source file:

- `TOKENS_CSS` from docs/design/tokens.css, the design system's only source of values;
- `PAGE_CSS`, `BANNER_CSS` and `SETTINGS_CSS` from the component rules in src/core/ui/.

`@import "<relative path>";` lines are inlined, comments and blank lines are dropped, and the
rest is kept line for line, so the bundles stay readable (rule 2). No value is copied by hand:
a token changes in tokens.css and nowhere else. The output is gitignored and regenerated by the
tasks that need it.

Usage: gen_styles.py
"""

import re
from pathlib import Path

from repo import ROOT, fail

UI = ROOT / "src" / "core" / "ui"
SOURCES = (
    ("TOKENS_CSS", ROOT / "docs" / "design" / "tokens.css"),
    ("PAGE_CSS", UI / "styles.css"),
    ("BANNER_CSS", UI / "banner.css"),
    ("SETTINGS_CSS", UI / "settings.css"),
)
OUTPUT = UI / "styles.gen.ts"
IMPORT = re.compile(r'^@import\s+"([^"]+)";\s*$')
COMMENT = re.compile(r"/\*.*?\*/", re.DOTALL)


def inline(path: Path, seen: tuple[Path, ...] = ()) -> str:
    if path in seen:
        fail(f"{path.relative_to(ROOT).as_posix()}: @import cycle")
    if not path.is_file():
        fail(f"{path.relative_to(ROOT).as_posix()}: not found")
    lines: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = IMPORT.match(line)
        if match is None:
            lines.append(line)
        else:
            lines.append(inline((path.parent / match.group(1)).resolve(), (*seen, path)))
    return "\n".join(lines)


def compact(css: str) -> str:
    without_comments = COMMENT.sub("", css)
    if "/*" in without_comments or "*/" in without_comments:
        fail("unbalanced CSS comment")
    lines = [line.rstrip() for line in without_comments.splitlines()]
    return "\n".join(line for line in lines if line.strip()) + "\n"


def stylesheet(name: str) -> str:
    """The CSS text of one constant, exactly as styles.gen.ts holds it."""
    source = dict(SOURCES).get(name)
    if source is None:
        fail(f"unknown stylesheet {name}")
    return compact(inline(source.resolve()))


def template_literal(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
    return f"`{escaped}`"


def render() -> str:
    lines = [
        "// Generated by scripts/gen_styles.py from docs/design/tokens.css and src/core/ui/*.css.",
        "// Do not edit.",
        "",
    ]
    for name, source in SOURCES:
        relative = source.relative_to(ROOT).as_posix()
        lines += [
            f"/** {relative}, without comments. */",
            f"export const {name} = {template_literal(stylesheet(name))};",
            "",
        ]
    return "\n".join(lines)


def main() -> None:
    text = render()
    if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
